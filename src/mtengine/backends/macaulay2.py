"""Macaulay2 adapter."""
from __future__ import annotations

import re

from ..core import EngineError, run_process, tail


def run(code: str, timeout: float = 600) -> str:
    """Run a Macaulay2 script; return its standard output."""
    r, _ = run_process(["M2", "--script", "prog.m2"], files={"prog.m2": code}, timeout=timeout)
    if r.returncode != 0:
        raise EngineError(f"Macaulay2 failed (exit {r.returncode}):\n{tail(r.stderr or r.stdout)}")
    return r.stdout


def _linear_form(weight: list[int]) -> str:
    terms = [f"({c})*R_{i}" for i, c in enumerate(weight) if c]
    if not terms:
        raise EngineError("GKM edge with zero weight")
    return "+".join(terms)


def gkm_betti(n_vars: int, n_vertices: int, edges: list[tuple[int, int, list[int]]],
              timeout: float = 1800) -> dict:
    """Betti numbers of a GKM graph from the Hilbert series of its ring of graph functions.

    The ring is the kernel of  (+)_v R -> (+)_edges R/(alpha_e),  (f_v) |-> (f_p - f_q),
    R = Q[t_1..t_n] with deg t_i = 1 (so T stands for cohomological degree 2). For an
    equivariantly formal GKM manifold, Hilb = (sum_k beta_2k T^k) / (1-T)^n.
    """
    if not edges:
        raise EngineError("GKM graph without edges")
    rows = ",".join(f"({a},{b})" for a, b, _ in edges)
    wts = ",".join(_linear_form(w) for _, _, w in edges)
    code = f"""
R = QQ[t_1..t_{n_vars}];
N = {n_vertices};
rows = {{{rows}}};
wts = {{{wts}}};
Tgt = directSum apply(wts, al -> coker matrix {{{{al}}}});
M = matrix apply(#rows, e -> (r := rows#e; apply(N, c -> if c == r#0 then 1_R else if c == r#1 then -1_R else 0_R)));
K = kernel map(Tgt, R^N, M);
hs = reduceHilbert hilbertSeries K;
num = numerator hs;
T = (ring num)_0;
print("BETTI " | toString apply(first degree num + 1, k -> coefficient(T^k, num)));
print("DENOM " | toString denominator hs);
"""
    out = run(code, timeout)
    betti = re.search(r"BETTI \{([^}]*)\}", out)
    denom = re.search(r"DENOM (.*)", out)
    if not betti:
        raise EngineError(f"could not parse Macaulay2 output:\n{tail(out)}")
    return {"betti": [int(x) for x in betti.group(1).split(",")],
            "denominator": denom.group(1).strip() if denom else None}



def orlik_solomon_hilbert(n: int, circuits: list[list[int]], timeout: float = 1800) -> list[int]:
    """Hilbert function of the Orlik-Solomon algebra E/I: E is the exterior algebra on
    e_0..e_{n-1} over Q, I is generated by the boundaries d(e_C) of the circuits C (a loop {i}
    gives d(e_i) = 1, so I = E). Returned degree by degree up to the last nonzero value."""
    gens = [f"bd {{{','.join(map(str, c))}}}" for c in circuits] or ["0_E"]
    code = f"""E = QQ[e_0..e_{n - 1}, SkewCommutative=>true];
bd = C -> sum(#C, k -> (-1)^k * product(drop(C, {{k,k}}), i -> e_i) * 1_E);
A = E / ideal({{{', '.join(gens)}}});
scan(0..{n}, d -> print hilbertFunction(d, A));
"""
    h = [int(x) for x in run(code, timeout).split()]
    while h and h[-1] == 0:
        h.pop()
    return h


def chow_ring_hilbert(n: int, flats: list[list[int]], top: list[int], augmented: bool = False,
                      timeout: float = 1800) -> list[int]:
    """Hilbert function of the Chow ring of a loopless matroid on 0..n-1 from its presentation,
    given all flats (`top` is the ground set).

    Chow ring (Adiprasito-Huh-Katz): generators x_F for the nonempty proper flats, relations
    x_F x_G for incomparable F, G and sum_{F contains i} x_F - sum_{F contains j} x_F.
    Augmented Chow ring (Braden-Huh-Matherne-Proudfoot-Wang): generators x_F for the proper
    flats (the empty flat included) and y_i for the elements, relations
    y_i - sum_{F not containing i} x_F, x_F x_G for incomparable F, G, and y_i x_F for i not in F."""
    fl = [set(F) for F in flats if set(F) != set(top) and (augmented or F)]
    m = len(fl)
    if m == 0 and not augmented:
        return [1]
    gens = [f"x_{a}*x_{b}" for a in range(m) for b in range(a + 1, m)
            if not (fl[a] <= fl[b] or fl[b] <= fl[a])]
    if augmented:
        for i in range(n):
            s = " + ".join(f"x_{a}" for a in range(m) if i not in fl[a]) or "0"
            gens.append(f"y_{i} - ({s})")
            gens += [f"y_{i}*x_{a}" for a in range(m) if i not in fl[a]]
        ring = f"QQ[x_0..x_{m - 1}, y_0..y_{n - 1}]"
    else:
        for i in range(1, n):
            a = " + ".join(f"x_{k}" for k in range(m) if 0 in fl[k]) or "0"
            b = " + ".join(f"x_{k}" for k in range(m) if i in fl[k]) or "0"
            gens.append(f"({a}) - ({b})")
        ring = f"QQ[x_0..x_{m - 1}]"
    body = ",\n  ".join(gens) or "0_R"
    code = f"""R = {ring};
A = R / ideal(
  {body});
scan(0..{n + 1}, d -> print hilbertFunction(d, A));
"""
    h = [int(x) for x in run(code, timeout).split()]
    if h[-1] != 0:
        raise EngineError("Chow ring is not zero above the rank: the input is not a loopless matroid?")
    while h and h[-1] == 0:
        h.pop()
    return h
