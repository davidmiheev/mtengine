"""gfan adapter: tropical varieties of homogeneous prime ideals."""
from __future__ import annotations

import itertools
import re
import string

from ..core import EngineError, run_process, tail


def _safe_names(k: int) -> list[str]:
    # gfan 0.6.2 mis-parses variable names when one is a prefix of another (p1 vs p12):
    # it aborts with "Monomial p1^27 not found in p1^36". Equal-length two-letter names
    # can never be prefixes of each other.
    return ["".join(p) for p in itertools.product(string.ascii_lowercase, repeat=2)][:k]


def tropical_variety(variables: list[str], generators: list[str], timeout: float = 3600) -> dict:
    """dim, lineality and f-vector of trop V(I) (I generated by `generators`, assumed prime
    and homogeneous), via `gfan _tropicalstartingcone | gfan _tropicaltraverse`."""
    if len(variables) > 676:
        raise EngineError("too many variables")
    names = _safe_names(len(variables))
    key = dict(zip(variables, names))
    gens = []
    for g in generators:
        for v in sorted(variables, key=len, reverse=True):
            g = re.sub(rf"(?<![A-Za-z0-9_]){re.escape(v)}(?![A-Za-z0-9_])", key[v], g)
        gens.append(g)
    text = f"Q[{','.join(names)}]\n{{{','.join(gens)}}}\n"
    r, _ = run_process(["sh", "-c", "gfan _tropicalstartingcone < in.gfan | gfan _tropicaltraverse"],
                       files={"in.gfan": text}, timeout=timeout)
    out = r.stdout
    if r.returncode != 0 or "F_VECTOR" not in out:
        raise EngineError(f"gfan failed (exit {r.returncode}):\n{tail(r.stderr or out)}")
    def field(name):
        m = re.search(rf"^{name}\n([^\n]*)", out, re.M)
        return m.group(1).strip() if m else None
    return {"ambient_dim": int(field("AMBIENT_DIM")), "dim": int(field("DIM")),
            "lineality_dim": int(field("LINEALITY_DIM")),
            "f_vector": [int(x) for x in field("F_VECTOR").split()],
            "pure": field("PURE") == "1", "variable_key": key}
